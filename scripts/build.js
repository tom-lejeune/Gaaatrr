#!/usr/bin/env node
/* Builds everything the Max device loads into device/:
 *   gaaatrr.v8.js      core + engine, one file for the [v8] object
 *   gaaatrr-ui.html    the jweb UI with the core inlined
 *   Gaaatrr.maxpat     the patcher (see scripts/make-patch.js)
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const out = path.join(root, 'device');
fs.mkdirSync(out, { recursive: true });

const core = read('src/core.js');
const banner = '/* GENERATED by scripts/build.js from src/ — edit the sources, not this file. */\n';

fs.writeFileSync(path.join(out, 'gaaatrr.v8.js'), banner + core + '\n' + read('src/engine.js'));

const ui = read('src/ui.html');
if (!ui.includes('/*__CORE__*/')) throw new Error('src/ui.html is missing the /*__CORE__*/ marker');
fs.writeFileSync(
  path.join(out, 'gaaatrr-ui.html'),
  ui.replace('/*__CORE__*/', () => core.replace(/<\/script/gi, '<\\/script'))
);

require('./make-patch.js').write(path.join(out, 'Gaaatrr.maxpat'));
console.log('built device/: gaaatrr.v8.js, gaaatrr-ui.html, Gaaatrr.maxpat');
